// Encodes the selected game screenshots (docs/screens/selection.json → raw PNGs in docs/screens/raw/) into
// src/lib/screens/*.webp, generates src/lib/screens/index.ts for the homepage, and builds static/og.jpg (1200×630 link
// preview: the hero frame with the app icon). Run `pnpm screens` after changing the selection or recapturing.
//
// selection.json: { "hero": "<raw file>", "og": "<raw file>", "shots": [{ "id", "file", "caption": "<message key>" }] }
// The hero and OG frames are usually HUD free versions (raw/clean/); the carousel keeps the HUD, like a store listing.
// `caption` is a Paraglide message key (generated copy, docs/copy/site-prompt.md); it doubles as the image's alt text.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const path = (relative) => fileURLToPath(new URL(`../${relative}`, import.meta.url));
const raw = (file) => path(`docs/screens/raw/${file}`);
const selection = JSON.parse(readFileSync(path('docs/screens/selection.json'), 'utf8'));
const outDir = path('src/lib/screens');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// 1920 px is enough for a 2× carousel slide (~700 CSS px at most) and the hero; enhanced-img derives the smaller sizes
const encode = (file, name) => sharp(raw(file)).resize(1920, 1080, { fit: 'cover' }).webp({ quality: 90, smartSubsample: true }).toFile(`${outDir}/${name}.webp`);

await encode(selection.hero, 'hero');
for (const shot of selection.shots) await encode(shot.file, shot.id);

const camel = (id) => id.replace(/-(\w)/g, (_, char) => char.toUpperCase());
const index = `// Generated by scripts/screens.mjs from docs/screens/selection.json. Do not edit.
import type { Picture } from '@sveltejs/enhanced-img';
import { m } from '#lib/paraglide/messages.js';
import heroImage from './hero.webp?enhanced';
${selection.shots.map((shot) => `import ${camel(shot.id)} from './${shot.id}.webp?enhanced';`).join('\n')}

export type Shot = { id: string; image: Picture; caption: () => string };

/** Large screenshot in the hero phone */
export const hero: Picture = heroImage;

/** Link preview image (static/og.jpg, 1200×630) */
export const ogImage = '/og.jpg';

/** Carousel slides, in order */
export const shots: Shot[] = [
${selection.shots.map((shot) => `\t{ id: '${shot.id}', image: ${camel(shot.id)}, caption: m.${shot.caption} }`).join(',\n')}
];
`;
writeFileSync(`${outDir}/index.ts`, index);

// OG image: the frame cropped to 1200×630, warm vignette, rounded app icon in the corner
const icon = await sharp(path('docs/art/app-icon-1024.png'))
	.resize(150, 150)
	.composite([{ input: Buffer.from('<svg width="150" height="150"><rect width="150" height="150" rx="34" ry="34"/></svg>'), blend: 'dest-in' }])
	.png()
	.toBuffer();
const vignette = Buffer.from(
	'<svg width="1200" height="630"><defs><radialGradient id="v" cx="50%" cy="45%" r="75%"><stop offset="60%" stop-color="#120d09" stop-opacity="0"/><stop offset="100%" stop-color="#120d09" stop-opacity="0.65"/></radialGradient></defs><rect width="1200" height="630" fill="url(#v)"/></svg>'
);
await sharp(raw(selection.og))
	.resize(1200, 630, { fit: 'cover', position: 'centre' })
	.composite([
		{ input: vignette, top: 0, left: 0 },
		{ input: icon, top: 630 - 150 - 36, left: 36 }
	])
	.jpeg({ quality: 86, mozjpeg: true })
	.toFile(path('static/og.jpg'));

console.log(`${selection.shots.length} screenshots + hero → src/lib/screens/, static/og.jpg`);
